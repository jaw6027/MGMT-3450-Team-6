import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(process.env.TEST_URL || 'http://127.0.0.1:5173');
  await page.getByRole('heading',{name:'Marketing overview.'}).waitFor();
  const total=()=>page.locator('.metric').first().locator('strong').innerText();
  assert.equal(await total(),'48');
  await page.locator('#channel').selectOption('LinkedIn');
  assert.equal(await total(),'12');
  await page.locator('#period').selectOption('7');
  await page.locator('#audience').selectOption('Procurement');
  assert.equal(await total(),'1');
  await page.locator('#lead-rows').getByRole('button',{name:/Edit /}).first().click();
  await page.getByLabel('Owner',{exact:true}).fill('Demo reviewer');
  await page.getByLabel('Next action',{exact:true}).fill('Arrange a discovery call');
  await page.getByRole('button',{name:'Save lead'}).click();
  await page.reload();
  await page.locator('#channel').selectOption('LinkedIn');
  await page.locator('#period').selectOption('7');
  await page.locator('#audience').selectOption('Procurement');
  assert.ok((await page.locator('#lead-rows').innerText()).includes('Demo reviewer'));
  const pending=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export leads'}).click();
  const download=await pending;
  const csv=await fs.readFile(await download.path(),'utf8');
  assert.ok(csv.includes('Demo reviewer'));
  assert.equal(csv.split('\r\n').length,2);
  await page.getByRole('searchbox',{name:'Search companies'}).fill('no such fictional organization');
  assert.ok((await page.locator('#lead-rows').innerText()).includes('No matching leads'));
  await page.getByRole('searchbox',{name:'Search companies',exact:true}).fill('');
  await page.locator('#period').selectOption('30');
  await page.locator('#channel').selectOption('All channels');
  await page.locator('#audience').selectOption('All audiences');
  await page.screenshot({path:'/tmp/beyond-dashboard-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));
  await page.locator('#lead-rows').getByRole('button',{name:/Edit /}).first().click();
  assert.ok(await page.locator('#edit-dialog').isVisible());
  await page.keyboard.press('Escape');
  await page.screenshot({path:'/tmp/beyond-dashboard-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Browser checks passed: filters, persistent editing, filtered CSV, search, mobile layout, dialog, and no runtime errors.');
} finally { await browser.close(); }
